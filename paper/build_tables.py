"""Generate every number and table of the paper from the repository, so that text and code never
diverge.

    python paper/build_tables.py        # writes paper/generated/numbers.tex and paper/generated/tab_*.tex

Inputs (nothing is typed by hand here):
- outputs/*.csv, written by `python -m chronosim.run`;
- docs/literature_check_factor2.md, for the counts of the literature search;
- docs/equation_transcription.md, for the number of transcribed equations;
- requirements.txt and git, for the software versions and the commit.

Each macro is a number with its origin given in the text or table where it is used. A value that
cannot be found makes the script stop with an error: no silent default.
"""

from __future__ import annotations

import csv
import re
import subprocess
from pathlib import Path

import mpmath as mp

mp.mp.dps = 40  # the CSVs carry 20 significant digits; read them without loss

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "outputs"
GEN = Path(__file__).resolve().parent / "generated"


def rows(name):
    with open(OUT / name, newline="", encoding="utf-8") as fh:
        return list(csv.DictReader(fh))


def num(x):
    return mp.mpf(x)


def tex(x, sig=3):
    """A number as LaTeX with sig significant digits: 3.96e-20 -> 3.96\\times10^{-20}; 0.5 -> 0.5;
    exact zero -> 0. Read from the CSV string with mpmath, so no digit is lost on the way."""
    x = mp.mpf(x)
    if x == 0:
        return "0"
    s = mp.nstr(x, sig, min_fixed=-3, max_fixed=4)
    if "e" not in s:
        return s[:-2] if s.endswith(".0") else s
    m, e = s.split("e")
    e = int(e)
    return (f"{m}\\times" if m not in ("1.0", "1", "-1.0", "-1") else ("-" if m.startswith("-") else "")) + f"10^{{{e}}}"


def full(x):
    """The value exactly as stored in the CSV (20 significant digits), e.g. 1.9999999999999999999."""
    return str(x)


class Macros:
    def __init__(self):
        self.items = {}

    def __setitem__(self, name, value):
        if not re.fullmatch(r"[A-Za-z]+", name):
            raise ValueError(f"macro name must be letters only: {name}")
        if name in self.items:
            raise ValueError(f"macro defined twice: {name}")
        self.items[name] = value

    def write(self, path):
        lines = ["% Generated by paper/build_tables.py. Do not edit by hand."]
        lines += [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in sorted(self.items.items())]
        path.write_text("\n".join(lines) + "\n", encoding="utf-8")


# Grid points quoted in the text. The same strings select the CSV rows, so a label cannot drift
# from the value it labels: a string absent from the CSV makes max() fail on an empty list.
EPS_LARGE, EPS_SMALL = "1e-2", "1e-8"          # F1, eps / D
B_LARGE, B_SMALL = "1e-2", "1e-6"              # F2, b / D
DELTA_LARGE, DELTA_SMALL = "1e-2", "1e-6"      # F3, Delta / D, on the axis
DB_LARGE, DB_SMALL = "1e-2", "1e-6"            # F4, Delta / b
X_LINEAR, X_HALF = "0.25", "0.5"               # F3, X / D on the axis


def summary():
    return {r["key"]: r for r in rows("summary.csv")}


def literature_counts():
    text = (ROOT / "docs" / "literature_check_factor2.md").read_text(encoding="utf-8")
    m = re.search(r"INSPIRE: (\d+) trabalhos que citam Kim & Thorne; (\d+) com arXiv", text)
    m2 = re.search(r"\| (\d+) mencionam Kim & Thorne", text)
    m3 = re.search(r"(\d+) dos (\d+) trabalhos citantes não têm versão no arXiv", text)
    if not (m and m2 and m3):
        raise SystemExit("literature counts not found in docs/literature_check_factor2.md")
    citing, arxiv = int(m.group(1)), int(m.group(2))
    mention, missing, total = int(m2.group(1)), int(m3.group(1)), int(m3.group(2))
    if total != citing or citing - arxiv != missing:
        raise SystemExit("literature counts in docs/literature_check_factor2.md are inconsistent")
    return citing, arxiv, mention, missing


def transcribed_equations():
    text = (ROOT / "docs" / "equation_transcription.md").read_text(encoding="utf-8")
    part = text.split("# Echeverria")[0]
    table = [l for l in part.splitlines() if re.match(r"^\| \d+[a-z]? \| \d{4} \|", l)]
    agree = [l for l in table if l.rstrip().endswith("| sim |")]
    stated = re.search(r"as (\d+) equações conferem", part)
    if not stated or int(stated.group(1)) != len(table) or len(agree) != len(table):
        raise SystemExit("transcription table and its stated count disagree")
    return len(table)


RELEASE_TAG = "v0.2.0"


def git(*args):
    return subprocess.run(["git", *args], cwd=ROOT, capture_output=True, text=True)


def release(require):
    """The release the paper cites. If the tag exists, HEAD must be exactly the tagged commit, with a
    clean tree; otherwise the script stops. If the tag does not exist yet, the paper says PENDING
    (and with require=True the script stops)."""
    tagged = git("rev-list", "-n", "1", RELEASE_TAG)
    if tagged.returncode != 0:
        if require:
            raise SystemExit(f"tag {RELEASE_TAG} does not exist")
        return f"PENDING (release {RELEASE_TAG} not yet tagged)"
    head = git("rev-parse", "HEAD").stdout.strip()
    if tagged.stdout.strip() != head:
        raise SystemExit(f"HEAD {head[:12]} is not the commit of tag {RELEASE_TAG} ({tagged.stdout.strip()[:12]})")
    if git("status", "--porcelain", "--untracked-files=no").stdout.strip():
        raise SystemExit("the working tree has uncommitted changes; the paper must be built from the tagged release")
    return f"{RELEASE_TAG} (commit \\texttt{{{head[:12]}}})"


def trailers():
    """Commits reachable from HEAD: non-merge commits with and without a Co-Authored-By trailer
    naming Claude, and merge commits (with and without it)."""
    log = git("log", "--format=%H|%P|%(trailers:key=Co-Authored-By,valueonly,separator=;)").stdout.splitlines()
    out = {"plain_with": 0, "plain_without": 0, "merge_with": 0, "merge_without": 0}
    for line in log:
        _, parents, co = line.split("|", 2)
        kind = "merge" if len(parents.split()) > 1 else "plain"
        out[f"{kind}_{'with' if 'Claude' in co else 'without'}"] += 1
    return out


def versions():
    req = (ROOT / "requirements.txt").read_text(encoding="utf-8")
    pins = dict(re.findall(r"^([A-Za-z0-9_.-]+)==(\S+)", req, flags=re.M))
    py = re.search(r"Python (\d+\.\d+\.\d+)", req)
    return pins, py.group(1) if py else None


def main(argv=None):
    import argparse
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--release", action="store_true", help=f"require the tag {RELEASE_TAG} at HEAD (final build)")
    args = ap.parse_args(argv)
    GEN.mkdir(exist_ok=True)
    M = Macros()
    S = summary()

    # Phase 1 (Li & Gott)
    val = rows("validation.csv")
    M["PhaseOnePoints"] = str(len(val))
    M["PhaseOneWorst"] = tex(S["phase1_worst_rel_error"]["value"])
    M["PhaseOneSlopeDev"] = tex(num(S["phase1_horizon_slope"]["value"]) + 4)
    zero = [r for r in val if r["b"] == "2pi"]
    worst0 = max(zero, key=lambda r: abs(num(r["rho_computed"])))
    M["PhaseOneTwoPiMax"] = tex(abs(num(worst0["rho_computed"])))
    M["PhaseOneTwoPiXi"] = worst0["xi"]
    M["PhaseOneTwoPiRel"] = tex(worst0["max_err_over_scale"])

    # Arbiters
    th = rows("kt_thermal_arbiter.csv")
    by = lambda op: [r for r in th if r["operator"] == op]
    M["ThermalTemps"] = ", ".join(r["T"] for r in by("eq4a"))
    M["ThermalEqFourA"] = full(by("eq4a")[0]["rho_over_stefan_boltzmann"])
    M["ThermalHalf"] = full(by("with_half")[0]["rho_over_stefan_boltzmann"])
    M["ThermalPressureDev"] = tex(max(abs(num(r["worst_3p_over_rho_minus_1"])) for r in th))
    M["ThermalTrace"] = tex(max(abs(num(r["trace_over_rho"])) for r in th))
    M["ThermalFDErr"] = tex(max(abs(num(r["fd_err"])) for r in th))
    modes = rows("kt_thermal_modes.csv")
    M["ModesMaxDiff"] = tex(max(num(r["rel_diff"]) for r in modes))
    un = rows("kt_unruh_arbiter.csv")
    M["UnruhHalfDev"] = tex(max(abs(num(r["with_half_over_ref"]) - 1) for r in un))
    M["UnruhEqFourADev"] = tex(max(abs(num(r["eq4a_over_ref"]) - 2) for r in un))
    arb = rows("kt_arbiter_eq4a_vs_eq11.csv")
    M["ArbiterRatioDev"] = tex(max(abs(num(r["worst_ratio_minus_2"])) for r in arb))
    M["ArbiterXis"] = ", ".join(r["xi"] for r in arb)

    # F1
    for key, name in (("eq33", "FOneEqThirtyThree"), ("eq34", "FOneEqThirtyFour"), ("eq37", "FOneEqThirtySeven"),
                      ("fixed_point", "FOneEqTwentyNine"), ("eq31", "FOneEqThirtyOne")):
        M[name] = tex(S[f"f1_{key}"]["value"])
    f1 = rows("kim_thorne_f1.csv")
    e2 = [num(r["eq38_rel_err"]) for r in f1 if r["eps_over_D"] == EPS_LARGE]
    e8 = [num(r["eq38_rel_err"]) for r in f1 if r["eps_over_D"] == EPS_SMALL]
    M["EpsLarge"], M["EpsSmall"] = tex(EPS_LARGE), tex(EPS_SMALL)
    M["FOneEqThirtyEightAtTwo"] = tex(max(e2))
    M["FOneEqThirtyEightAtEight"] = tex(max(e8))

    # F2
    f2 = rows("kim_thorne_f2.csv")
    small = [r for r in f2 if r["b_over_D"] == B_SMALL]
    M["BLarge"], M["BSmall"] = tex(B_LARGE), tex(B_SMALL)
    M["FTwoThroatSmall"] = tex(max(abs(num(r["throat_psi_over_eq47_minus_1"])) for r in small))
    M["FTwoBetweenSmall"] = tex(max(abs(num(r["between_psi_over_eq64_zeta_minus_1"])) for r in small))
    large = [r for r in f2 if r["b_over_D"] == B_LARGE]
    M["FTwoThroatLarge"] = tex(max(abs(num(r["throat_psi_over_eq47_minus_1"])) for r in large))
    M["FTwoBetweenLarge"] = tex(max(abs(num(r["between_psi_over_eq64_zeta_minus_1"])) for r in large))
    M["FTwoLapse"] = tex(S["f2_eq57_lapse_dev"]["value"])

    # F3
    f3 = rows("kim_thorne_f3.csv")
    axis = [r for r in f3 if r["rho_over_X"] == "0"]
    M["FThreeDevSmall"] = tex(max(num(r["eq4a_worst_dev"]) for r in axis if r["delta_over_D"] == DELTA_SMALL))
    M["FThreeDevLarge"] = tex(max(num(r["eq4a_worst_dev"]) for r in axis if r["delta_over_D"] == DELTA_LARGE))
    M["FThreeHalfSmall"] = tex(max(abs(num(r["with_half_TT_over_eq67"]) - mp.mpf(1) / 2) for r in axis if r["delta_over_D"] == DELTA_SMALL))
    M["DeltaLarge"], M["DeltaSmall"] = tex(DELTA_LARGE), tex(DELTA_SMALL)
    xs = sorted({r["X_over_D"] for r in axis})
    if xs != [X_LINEAR, X_HALF]:
        raise SystemExit(f"F3 on-axis rows use X/D = {xs}; the text describes {X_LINEAR} and {X_HALF}")
    M["FThreeX"], M["FThreeXHalf"] = X_LINEAR, X_HALF
    M["FThreeFD"] = tex(max(num(r["fd_err"]) for r in f3))
    M["FThreeSlopeDev"] = tex(num(S["f3_slope_eq4a"]["value"]) + 3)
    M["FThreeSlopeHalfDev"] = tex(num(S["f3_slope_with_half"]["value"]) + 3)
    off = [r for r in f3 if r["rho_over_X"] != "0"]
    M["FThreeOffAxisMax"] = tex(max(num(r["eq4a_worst_dev"]) for r in off))

    # F4
    f4 = rows("kim_thorne_f4.csv")
    M["FFourDevSmall"] = tex(max(num(r["eq4a_dev_transverse"]) for r in f4 if r["delta_over_b"] == DB_SMALL))
    M["FFourDevLarge"] = tex(max(num(r["eq4a_dev_transverse"]) for r in f4 if r["delta_over_b"] == DB_LARGE))
    M["FFourLiteralSmall"] = tex(max(num(r["eq4a_dev_literal"]) for r in f4 if r["delta_over_b"] == DB_SMALL))
    M["FFourHalfRatio"] = tex(max(abs(num(r["with_half_TT_over_eq51"]) - mp.mpf(1) / 2) for r in f4))
    M["DbLarge"], M["DbSmall"] = tex(DB_LARGE), tex(DB_SMALL)
    M["FFourFD"] = tex(max(num(r["fd_err"]) for r in f4))
    M["FFourSlopeDev"] = tex(num(S["f4_slope_eq4a"]["value"]) + 3)

    # F5
    M["FFiveEqFortyThree"] = tex(S["f5_eq43_max_dev"]["value"])
    M["FFiveEqSixtyTwo"] = tex(S["f5_eq62_max_dev"]["value"])
    f5 = rows("kim_thorne_f5.csv")
    M["FFiveLimitN"] = f5[0]["N"]
    M["FFiveFortyFourAMax"] = tex(max(num(r["dev_eq44a"]) for r in f5))
    M["FFiveFortyFourAMin"] = tex(min(num(r["dev_eq44a"]) for r in f5))

    # F6
    f6 = rows("kim_thorne_f6.csv")
    q = lambda name: [r for r in f6 if r["quantity"] == name]
    M["FSixEqSixtyNine"] = tex(q("eq69_max_dev")[0]["value"])
    M["FSixEqSixtyEight"] = tex(abs(num(q("eq68_dev")[0]["value"])))
    e54 = q("eq54_dev")
    M["FSixEqFiftyFourFirst"] = tex(e54[0]["value"])
    M["FSixEqFiftyFourLast"] = tex(e54[-1]["value"])
    M["FSixEqFiftyFourFirstAt"] = e54[0]["parameter"].split("= ")[1]
    M["FSixEqFiftyFourLastAt"] = e54[-1]["parameter"].split("= ")[1]
    M["FSixEqFiftyThree"] = tex(abs(num(q("eq53_ln_coefficient_dev")[0]["value"])))

    # F7
    f7 = rows("kim_thorne_f7.csv")
    dens = [r for r in f7 if r["quantity"].startswith("T⁰⁰_max")][0]
    M["FSevenPrinted"] = tex(dens["printed"])
    M["FSevenRecomputed"] = tex(dens["recomputed"])

    heur = {r["name"]: r for r in rows("heuristics.csv")}
    M["WorkingDigits"] = heur["dps"]["value"]

    # Records
    citing, arxiv, mention, missing = literature_counts()
    M["LitCiting"], M["LitArxiv"], M["LitMention"], M["LitMissing"] = map(str, (citing, arxiv, mention, missing))
    M["TranscribedEquations"] = str(transcribed_equations())
    pins, py = versions()
    M["VersionPython"] = py or "PENDING"
    M["VersionMpmath"], M["VersionNumpy"], M["VersionMatplotlib"] = pins["mpmath"], pins["numpy"], pins["matplotlib"]
    M["CodeRelease"] = release(args.release)
    t = trailers()
    if t["merge_with"]:
        raise SystemExit("a merge commit carries the trailer; the AI-assistance sentence assumes it does not")
    M["CommitsWithTrailer"], M["CommitsWithoutTrailer"], M["MergeCommits"] = map(str, (t["plain_with"], t["plain_without"], t["merge_without"]))
    # Table: F7 side by side. The printed column holds only values printed in Kim & Thorne, with page.
    lines = ["% Generated by paper/build_tables.py from outputs/kim_thorne_f7.csv.",
             "\\begin{tabular}{llll}", "\\toprule", "Quantity & Page & Printed (CITED) & Recomputed (DERIVED) \\\\", "\\midrule"]
    names = {"l_P / D (D = 1 m)": "$l_P/D$, $D = 1$\\,m", "(δL/L)_max, eq. 13, N − 1 = 0": "$(\\delta L/L)_{\\max}$, eq.~13",
             "densidade de Planck m_P/l_P³": "Planck density $m_P/l_P^3$", "T⁰⁰_max, eq. 14": "$T^{00}_{\\max}$, eq.~14",
             "Δt do corte de Hawking (δg^VP = 1, eq. 9c)": "Hawking's breakdown $\\Delta t$ ($D\\Delta t \\sim l_P^2$)"}
    not_in_kt = []
    for r in f7:
        if r["quantity"] not in names:
            raise SystemExit(f"F7 row without an English label: {r['quantity']}")
        unit = {"g/cm^3": "\\,g/cm$^3$", "l_P": "\\,$l_P$"}.get(r["unit"], "")
        page = re.match(r"Kim & Thorne \(1991\), p\. (\d+)", r["printed_source"])
        if page:
            printed, pg = f"${tex(r['printed'])}${unit}", page.group(1)
        else:
            printed, pg = "---", "---"
            src = re.match(r"(.+?) \((\d{4})\), p\. (\d+)", r["printed_source"])
            if not src:
                raise SystemExit(f"F7 printed source without a page: {r['printed_source']}")
            not_in_kt.append(f"{names[r['quantity']]}, printed in {src.group(1)} ({src.group(2)}), p.~{src.group(3)}")
        lines.append(f"{names[r['quantity']]} & {pg} & {printed} & ${tex(r['recomputed'])}${unit} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    (GEN / "tab_f7.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")
    M["FSevenNotInKT"] = "; ".join(not_in_kt).replace("&", "\\&")
    M.write(GEN / "numbers.tex")

    # Table: arbiters
    lines = ["% Generated by paper/build_tables.py from outputs/kt_thermal_arbiter.csv, kt_unruh_arbiter.csv, kt_arbiter_eq4a_vs_eq11.csv.",
             "\\begin{tabular}{llll}", "\\toprule",
             "Reference & Origin of the reference & eq.~4a as printed & with $\\tfrac12$ \\\\", "\\midrule"]
    t1 = [r for r in th if r["T"] == "1"]
    eq4a = [r for r in t1 if r["operator"] == "eq4a"][0]
    half = [r for r in t1 if r["operator"] == "with_half"][0]
    lines.append(f"Stefan--Boltzmann, $\\rho/(\\pi^2T^4/30)$, $T=1$ & closed form, checked by the Bose integral (COMPUTED) & ${full(eq4a['rho_over_stefan_boltzmann'])}$ & ${full(half['rho_over_stefan_boltzmann'])}$ \\\\")
    u = un[0]
    lines.append(f"Unruh, $\\rho/\\rho_{{\\rm ref}}$, $\\xi={u['xi']}$ & HEURISTIC (source not read) & ${full(u['eq4a_over_ref'])}$ & ${full(u['with_half_over_ref'])}$ \\\\")
    a = arb[0]
    ratio = mp.nstr(num(a["rho_eq4_over_scale"]) / num(a["rho_phase1_over_scale"]), 20)
    lines.append(f"Li \\& Gott eq.~11 (validated in phase 1), $\\xi={a['xi']}$ & COMPUTED & ${ratio}$ & --- (reference) \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    (GEN / "tab_arbiters.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {len(M.items)} macros and 2 tables to {GEN}")


if __name__ == "__main__":
    main()
