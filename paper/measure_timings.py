"""Measure the running times quoted in the paper (section Reproducibility) on this machine.

Runs, in order and from the repository root:
    python -m pytest
    python -m chronosim.run          (default run)
    python paper/build_tables.py
    make -C paper
and writes the wall-clock time of each, with the hardware (CPU model, logical CPUs, RAM) and the
operating system, to paper/generated/timings.json and paper/generated/timings.tex.

Nothing here is typed by hand: every value comes from the clock or from the system (/proc, uname,
/etc/os-release). If a command fails, the script stops and writes nothing.

    python paper/measure_timings.py
    make -C paper                     # again, so the PDF includes the new timings.tex

    python paper/measure_timings.py --tex-only   # rewrite timings.tex from timings.json, no new run
"""

import json
import platform
import subprocess
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
GEN = ROOT / "paper" / "generated"

STEPS = [
    ("pytest", "test suite", [sys.executable, "-m", "pytest", "-q"]),
    ("run", "default run", [sys.executable, "-m", "chronosim.run"]),
    ("tables", "numbers and tables", [sys.executable, "paper/build_tables.py"]),
    ("pdf", "PDF", ["make", "-C", "paper"]),
]


def cpu_model():
    for line in Path("/proc/cpuinfo").read_text().splitlines():
        if line.startswith("model name"):
            return line.split(":", 1)[1].strip()
    return platform.processor() or "unknown"


def ram_gib():
    for line in Path("/proc/meminfo").read_text().splitlines():
        if line.startswith("MemTotal:"):
            return int(line.split()[1]) / 1024 ** 2  # kB -> GiB
    raise SystemExit("MemTotal not found in /proc/meminfo")


def os_name():
    p = Path("/etc/os-release")
    if p.exists():
        for line in p.read_text().splitlines():
            if line.startswith("PRETTY_NAME="):
                return line.split("=", 1)[1].strip().strip('"')
    return platform.system()


def minutes_seconds(t):
    if t < 1:
        return "under 1\\,s"
    m, s = divmod(round(t), 60)
    return f"{m}\\,min\\,{s:02d}\\,s" if m else f"{s}\\,s"


def write_tex(data):
    esc = lambda s: s.replace("\\", "\\textbackslash{}").replace("&", "\\&").replace("_", "\\_").replace("%", "\\%").replace("#", "\\#")
    lines = ["% Generated by paper/measure_timings.py from timings.json (wall-clock times on the machine described below)."]
    for key, _, _ in STEPS:
        lines.append(f"\\newcommand{{\\Time{key.capitalize()}}}{{{minutes_seconds(data['seconds'][key])}}}")
    lines += [
        f"\\newcommand{{\\TimeCPU}}{{{esc(data['cpu'])}}}",
        f"\\newcommand{{\\TimeCores}}{{{data['logical_cpus']}}}",
        f"\\newcommand{{\\TimeRAM}}{{{data['ram_gib']:.1f}}}",
        f"\\newcommand{{\\TimeOS}}{{{esc(data['os'])}}}",
        f"\\newcommand{{\\TimeKernel}}{{{esc(data['kernel'])}}}",
        f"\\newcommand{{\\TimePython}}{{{data['python']}}}",
        f"\\newcommand{{\\TimeDate}}{{{data['measured']}}}",
    ]
    (GEN / "timings.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")


def main():
    import os

    if "--tex-only" in sys.argv[1:]:
        write_tex(json.loads((GEN / "timings.json").read_text(encoding="utf-8")))
        print(f"wrote {GEN / 'timings.tex'} from timings.json")
        return
    times = {}
    for key, _, cmd in STEPS:
        start = time.perf_counter()
        r = subprocess.run(cmd, cwd=ROOT, capture_output=True, text=True)
        times[key] = time.perf_counter() - start
        if r.returncode != 0:
            sys.stdout.write(r.stdout[-3000:])
            sys.stderr.write(r.stderr[-3000:])
            raise SystemExit(f"{' '.join(cmd)} failed (exit {r.returncode}); no timings written")
        print(f"{key}: {times[key]:.1f} s")
    data = {
        "seconds": {k: round(v, 1) for k, v in times.items()},
        "cpu": cpu_model(),
        "logical_cpus": os.cpu_count(),
        "ram_gib": round(ram_gib(), 1),
        "os": os_name(),
        "kernel": platform.release(),
        "python": platform.python_version(),
        "measured": time.strftime("%Y-%m-%d", time.gmtime()),
    }
    (GEN / "timings.json").write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    write_tex(data)
    print(f"wrote {GEN / 'timings.json'} and timings.tex")


if __name__ == "__main__":
    main()
